export const IDIOMAS = { es: 'Español', ca: 'Català', en: 'English', de: 'Deutsch' };

// Preferencia guardada, si no el idioma del navegador y, si no, español
function idiomaInicial() {
  try {
    const guardado = localStorage.getItem('idioma');
    if (guardado && Object.hasOwn(IDIOMAS, guardado)) return guardado;
  } catch { /* almacenamiento bloqueado: se sigue con el navegador */ }
  for (const l of navigator.languages || [navigator.language]) {
    const base = String(l).toLowerCase().split('-')[0];
    if (Object.hasOwn(IDIOMAS, base)) return base;
  }
  return 'es';
}

export const idioma = idiomaInicial();
const reglasPlural = new Intl.PluralRules(idioma);

export function t(clave, vars = {}) {
  let texto = TEXTOS[idioma][clave] ?? TEXTOS.es[clave] ?? clave;
  if (typeof texto === 'object') texto = texto[reglasPlural.select(Number(vars.n))] ?? texto.other;
  return texto.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}

export function guardarIdioma(nuevo) {
  try { localStorage.setItem('idioma', nuevo); } catch { /* sin almacenamiento: solo dura esta visita */ }
}

// Textos fijos del HTML: data-t (contenido) y data-t-aria (aria-label)
export function traducirDocumento() {
  document.documentElement.lang = idioma;
  document.title = t('docTitulo');
  document.querySelector('meta[name="description"]')?.setAttribute('content', t('descripcion'));
  if (idioma === 'es') return;
  document.querySelectorAll('[data-t]').forEach((el) => (el.textContent = t(el.dataset.t)));
  document.querySelectorAll('[data-t-aria]').forEach((el) => el.setAttribute('aria-label', t(el.dataset.tAria)));
}
